@tool("lint_python_syntax", "codegen", "Check Python file syntax via ast.parse")
def lint_python_syntax(path: str) -> Dict[str, Any]:
    try:
        ast.parse(Path(path).read_text(encoding="utf-8"))
        return {"path": path, "valid": True}
    except SyntaxError as e:
        return {"path": path, "valid": False, "error": str(e)}


@tool("lint_python_compile", "codegen", "Compile a Python file (py_compile) and report errors")
def lint_python_compile(path: str) -> Dict[str, Any]:
    import py_compile

    try:
        py_compile.compile(path, doraise=True)
        return {"path": path, "compiled": True}
    except py_compile.PyCompileError as e:
        return {"path": path, "compiled": False, "error": str(e)}


@tool("code_metrics", "codegen", "Basic code metrics of a Python file (lines, functions, classes)")
def code_metrics(path: str) -> Dict[str, Any]:
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    tree = ast.parse(text)
    funcs = sum(1 for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)))
    classes = sum(1 for n in ast.walk(tree) if isinstance(n, ast.ClassDef))
    return {
        "path": path,
        "lines": len(text.splitlines()),
        "chars": len(text),
        "functions": funcs,
        "classes": classes,
        "imports": sum(1 for n in ast.walk(tree) if isinstance(n, (ast.Import, ast.ImportFrom))),
    }


@tool("code_count_lines", "codegen", "Count total lines of code for a directory (python files)")
def code_count_lines(root: str = ".") -> Dict[str, Any]:
    total = 0
    files = 0
    for p in Path(root).rglob("*.py"):
        if "__pycache__" in str(p) or ".venv" in str(p):
            continue
        try:
            total += len(p.read_text(encoding="utf-8", errors="replace").splitlines())
            files += 1
        except Exception:
            continue
    return {"root": root, "files": files, "lines": total}


@tool("refactor_rename", "codegen", "Rename an identifier in a text/code (token-level)")
def refactor_rename(code: str, old: str, new: str) -> Dict[str, Any]:
    if not old:
        return {"error": "old name required"}
    pattern = re.compile(rf"\b{re.escape(old)}\b")
    return {"code": pattern.sub(new, code), "replacements": len(pattern.findall(code))}


@tool("refactor_strip_comments", "codegen", "Remove Python comments from source text (naive)")
def refactor_strip_comments(code: str) -> Dict[str, Any]:
    lines = []
    for line in code.splitlines():
        stripped = line.lstrip()
        if stripped.startswith("#"):
            continue
        idx = line.find(" #")
        lines.append(line[:idx] if idx >= 0 else line)
    return {"code": "\n".join(lines)}


@tool("refactor_dedupe_lines", "codegen", "Remove duplicate consecutive lines from text")
def refactor_dedupe_lines(text: str) -> Dict[str, Any]:
    out = []
    prev = None
    removed = 0
    for line in text.splitlines():
        if line == prev:
            removed += 1
            continue
        out.append(line)
        prev = line
    return {"text": "\n".join(out), "removed": removed}


@tool("docstring_generate", "codegen", "Generate a docstring skeleton for a function signature")
def docstring_generate(signature: str = "def f(x, y):") -> Dict[str, Any]:
    m = re.match(r"def\s+(\w+)\s*\((.*?)\)", signature)
    if not m:
        return {"error": "invalid signature"}
    name, params = m.group(1), m.group(2)
    param_lines = "\n".join(f"    {p.strip()}:" for p in params.split(",") if p.strip())
    doc = f'"""\n{name}.\n\nArgs:\n{param_lines}\n\nReturns:\n    \n"""'
    return {"docstring": doc}



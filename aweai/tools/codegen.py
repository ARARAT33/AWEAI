@tool("codegen_function", "codegen", "Generate a Python function stub from a signature")
def codegen_function(name: str = "my_function", params: str = "x", returns: str = "None", doc: str = "") -> Dict[str, Any]:
    code = f"def {name}({params}):\n    \"\"\"{doc or 'Auto-generated function.'}\"\"\"\n    return {returns}\n"
    return {"code": code, "language": "python"}


@tool("codegen_class", "codegen", "Generate a Python class stub")
def codegen_class(name: str = "MyClass", methods: str = '["__init__", "run"]') -> Dict[str, Any]:
    methods_list = json.loads(methods) if isinstance(methods, str) else methods
    lines = [f"class {name}:\n"]
    for m in methods_list:
        lines.append(f"    def {m}(self, *args, **kwargs):\n        \"\"\"Method {m}.\"\"\"\n        raise NotImplementedError\n")
    return {"code": "\n".join(lines), "language": "python"}


@tool("codegen_json_schema", "codegen", "Generate a JSON schema draft for a list of fields")
def codegen_json_schema(fields: str = '["id", "name", "value"]') -> Dict[str, Any]:
    flds = json.loads(fields) if isinstance(fields, str) else fields
    props = {f: {"type": "string"} for f in flds}
    schema = {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "type": "object",
        "properties": props,
        "required": flds,
    }
    return {"schema": schema}



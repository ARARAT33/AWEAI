@tool("markdown_table", "codegen", "Convert a JSON array of objects to a markdown table")
def markdown_table(rows: str) -> Dict[str, Any]:
    data = json.loads(rows) if isinstance(rows, str) else rows
    if not data or not isinstance(data[0], dict):
        return {"error": "rows must be a non-empty JSON array of objects"}
    headers = list(data[0].keys())
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in data:
        lines.append("| " + " | ".join(str(row.get(h, "")) for h in headers) + " |")
    return {"table": "\n".join(lines)}


@tool("json_to_yaml_hint", "codegen", "Convert JSON to a YAML-ish representation (no dependency)")
def json_to_yaml_hint(data: str) -> Dict[str, Any]:
    obj = json.loads(data) if isinstance(data, str) else data
    lines = []

    def render(o, indent=0):
        pad = "  " * indent
        if isinstance(o, dict):
            for k, v in o.items():
                if isinstance(v, (dict, list)):
                    lines.append(f"{pad}{k}:")
                    render(v, indent + 1)
                else:
                    lines.append(f"{pad}{k}: {v}")
        elif isinstance(o, list):
            for v in o:
                if isinstance(v, (dict, list)):
                    render(v, indent)
                else:
                    lines.append(f"{pad}- {v}")

    render(obj)
    return {"yaml": "\n".join(lines)}


@tool("template_apply", "codegen", "Apply simple {{var}} substitutions to a template string")
def template_apply(template: str, variables: str = "{}") -> Dict[str, Any]:
    vars_data = json.loads(variables) if isinstance(variables, str) else variables
    out = template
    for k, v in vars_data.items():
        out = out.replace("{{" + k + "}}", str(v))
    return {"rendered": out}


